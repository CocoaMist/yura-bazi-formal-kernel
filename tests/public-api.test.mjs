function nestedOpaqueCollections(value, path = 'api', seen = new Set(), result = []) {
  if (value == null || typeof value !== 'object' || seen.has(value)) return result;
  seen.add(value);
  if (value instanceof Map || ArrayBuffer.isView(value)) result.push(path);
  for (const [key, child] of Object.entries(value)) {
    nestedOpaqueCollections(child, `${path}.${key}`, seen, result);
  }
  return result;
}

