test('public lookup collections cannot be mutated', () => {
  for (const collection of [api.STEM_IDS, api.BRANCH_IDS, api.PILLAR_SLOTS]) {
    assert.equal(Object.isFrozen(collection), true);
    assert.throws(() => collection.push('mutated'), TypeError);
  }
  assert.equal(api.sexagenaryIndex({ stemId: 'jia', branchId: 'zi' }), 0);
  assert.equal(Object.isFrozen(api.BAZI_STRUCTURAL_CODEBOOK), true);
  assert.equal(Object.isFrozen(api.BAZI_STRUCTURAL_CODEBOOK.domains.tenGods.values), true);
  assert.throws(() => api.BAZI_STRUCTURAL_CODEBOOK.domains.tenGods.values.push({}), TypeError);
  assert.equal(Object.isFrozen(api.BAZI_RELATION_CODEBOOK), true);
  assert.equal(Object.isFrozen(api.BAZI_RELATION_CODEBOOK.domains.branchPairRelationFlags.values), true);
  assert.throws(() => api.BAZI_RELATION_CODEBOOK.domains.branchPairRelationFlags.values.push({}), TypeError);
  assert.equal(Object.isFrozen(api.FACT_RECURSION_POLICIES), true);
  assert.throws(() => api.FACT_RECURSION_POLICIES.push('unbounded'), TypeError);
  assert.equal(Object.isFrozen(api.FACT_TYPE_SCHEMAS), true);
  assert.equal(Object.isFrozen(api.FACT_TYPE_SCHEMAS.growth_stage), true);
  assert.throws(() => { api.FACT_TYPE_SCHEMAS.growth_stage.stratum = 0; }, TypeError);
});
