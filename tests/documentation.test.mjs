import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { compileOne } from './natal-fixtures.mjs';

test('contract Mermaid blocks contain the implemented P0-P2 route and no dead candidate output', async () => {
  const core = await readFile(new URL('../CORE.md', import.meta.url), 'utf8');
  const blocks = [...core.matchAll(/```mermaid\r?\n([\s\S]*?)```/g)].map((match) => match[1]);
  assert.ok(blocks.length >= 3);
  assert.ok(blocks.every((block) => /^flowchart\s/m.test(block)));
  const runtime = blocks.find((block) => block.includes('stop boundary'));
  for (const required of [
    'CalendarResolutionEnvelopeV1', 'NatalCompilationRequestV1',
    'NatalCalendarDecisionTraceV1', 'CanonicalChartCoordinateV2', 'pillarCode24',
    'RootPillarFact', 'HiddenStemOccurrenceFact', 'TenGodRelationFact',
    'GrowthStageFact', 'CanonicalFactGraphV4', 'DerivationRecord',
    'ProfileScopedStructuralCandidateSetV2', 'CompiledNatalArtifactV2',
    'CandidateCompilationResultV2', 'NatalCompilationBatchV2',
    'validation_failed', 'compilation_failed', 'internal_error',
    'ReleaseManifestV2', 'ResolvedReleaseContextV1',
  ]) assert.ok(runtime.includes(required), `runtime Mermaid missing ${required}`);
  assert.match(runtime, /CandidateSnapshotSetV2[\s\S]*total-map/);
  const architecture = blocks.find((block) => block.includes('SourceInterpretation'));
  for (const required of [
    'RuleDefinition', 'RuleProfile', 'RuleExecutionPlan', 'RuleEvaluator',
    'Resolution: accepted', 'Resolution: rejected', 'Resolution: indeterminate',
    'Resolution: conflict', 'JudgmentResult', 'StateMutationProposal',
    'Canonical EffectOpSet', 'FormalState at n', 'FormalState at n+1',
    'ProvenanceDAG', 'TemporalOverlayCompiler', 'CalibrationReport',
    'SelectedCompiledNatalArtifactRef', 'EvaluationContextBuilder',
    'natalProvenanceRoot', 'judgmentProvenanceRoot', 'stateProvenanceRoot',
    'calibrationProvenanceRoot', 'ExplicitEffectTemplate',
    'MutationAdmissionRejection', 'candidateManifestHash',
  ]) assert.ok(architecture.includes(required), `architecture Mermaid missing ${required}`);
  assert.equal(/COMPILE\s*-->\|"success"\|\s*COK/.test(architecture), false);
  assert.match(architecture, /ART\s*-->\s*COK\s*-->\s*BATCH/);
  assert.match(architecture, /TOC\s*-->\s*OVER[\s\S]*OVER\s*-->\s*CTXB/);
  assert.match(architecture, /CTX\s*-->\s*EVAL[\s\S]*PLAN\s*-->\s*EVAL/);
});

