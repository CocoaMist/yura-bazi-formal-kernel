test('verified runtime example is generated by the current compiler', () => {
  const run = compileOne({
    version: 'bazi.chart_snapshot.v2',
    snapshotId: 'snapshot:verified-runtime-example',
    subjectRef: 'subject:verified-runtime-example',
    validTimeRef: 'time:2000-07-19T16:00:00+08:00',
    traditionalSexClass: 'male',
    provenanceRef: 'calendar:verified-runtime-example',
    pillars: {
      year: { stemId: 'geng', branchId: 'chen' },
      month: { stemId: 'gui', branchId: 'wei' },
      day: { stemId: 'wu', branchId: 'yin' },
      hour: { stemId: 'geng', branchId: 'shen' },
    },
  });
  assert.equal(run.pillarCode24, 14_738_640);
  assert.equal(run.denseRank.index19, 143_456);
  assert.equal(run.canonicalFactGraph.facts.filter((row) => row.factType === 'root_pillar').length, 4);
  assert.equal(run.canonicalFactGraph.facts.filter((row) => /_occurrence$/.test(row.factType)).length, 20);
  const types = run.profileScopedStructuralCandidateSet.candidates.map((row) => row.candidateType);
  assert.ok(types.includes('stem_five_combination_candidate'));
  assert.ok(types.includes('branch_six_clash_candidate'));
  assert.ok(types.includes('branch_directional_punishment_candidate'));
  assert.ok(types.includes('partial_three_member_punishment_membership'));
});
